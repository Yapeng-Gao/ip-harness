export function toolCatalogLabel(toolId: string): string {
  const hit = TOOL_CATALOG.find((t) => t.id === toolId || t.name === toolId)
  if (hit) return hit.label
  return TOOL_ID_ALIASES[toolId] ?? toolId
}

